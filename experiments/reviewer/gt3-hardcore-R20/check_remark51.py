"""[Эксперимент] R20: замечание 5.1 (m=2: «покрыто FGT08 и Козловым 1986»).

U = y^2(1+x) - x^4, n=2, m=2. Условия следствия K0′ выполнены (u_2=y^2>=0, Sigma={(+-1,0)},
H=2>0), 0 — изолированная критическая точка, не минимум; R_omega(s) = -s^2 при omega=(1,0),
то есть j=4, g_4=-1<0 (теорема K0 применима).
Условие Козлова 1986 (по рецензии Zbl 0631.70018): V_2+V_m без локального минимума, где V_m —
следующая ненулевая форма. Здесь V_2+V_3 = y^2(1+x) >= 0 около нуля — локальный (нестрогий)
минимум, так что это условие НЕ выполнено. Значит, «покрыто Козловым 1986» верно не для всего
класса следствия K0′ при m=2 (FGT08 Thm A покрывает: ранг гессиана n-1 >= n-2).
"""
import sympy as sp
from reduced import reduced_series

x, y = X = sp.symbols('x y')
U = y**2 * (1 + x) - x**4
print('критические точки:', sp.solve([sp.diff(U, x), sp.diff(U, y)], [x, y], dict=True))
for sgn in (1, -1):
    R, ys, s, H0 = reduced_series(U, X, [sgn, 0], [[0, 1]], 2, 4)
    print('omega=(%d,0): H=%s  R(s)=%s' % (sgn, H0, R))
print('V_2+V_3 = y^2(1+x) >= 0 при |x|<1')

# Модельные случаи n=2 для трихотомии K0′: y^2+x^4 (строгий минимум), y^2-x^4 (g_4<0), y^2 (R==0)
for Um in (y**2 + x**4, y**2 - x**4, y**2):
    R, ys, s, H0 = reduced_series(Um, X, [1, 0], [[0, 1]], 2, 4)
    print('U =', Um, ': R(s) =', R)
